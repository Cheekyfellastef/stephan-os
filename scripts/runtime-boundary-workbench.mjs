#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import {
  RUNTIME_PATH_REGISTRY,
  registryAsSerializableObject,
} from '../shared/agents/runtimeBoundaryRegistry.mjs';

const SOURCE_EXTENSIONS = new Set(['.js', '.jsx', '.mjs', '.cjs', '.ts', '.tsx', '.ps1', '.vbs', '.json', '.md']);
const SKIP_DIRS = new Set(['.git', 'node_modules', '.cache']);
const WRITE_MARKERS = [
  'writeFile', 'writeFileSync', 'appendFile', 'appendFileSync', 'createWriteStream',
  'Set-Content', 'Add-Content', 'Out-File', '[System.IO.File]::Write',
];

async function walk(root, current = root, files = []) {
  const entries = await fs.readdir(current, { withFileTypes: true });
  for (const entry of entries) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const absolute = path.join(current, entry.name);
    if (entry.isDirectory()) await walk(root, absolute, files);
    else if (SOURCE_EXTENSIONS.has(path.extname(entry.name))) files.push(absolute);
  }
  return files;
}

export async function scanRuntimeProducers(repoRoot) {
  const files = await walk(repoRoot);
  const findings = [];
  for (const absolute of files) {
    const text = await fs.readFile(absolute, 'utf8').catch(() => '');
    const relativePath = path.relative(repoRoot, absolute).replaceAll('\\', '/');
    const lines = text.split(/\r?\n/);
    for (let index = 0; index < lines.length; index += 1) {
      const line = lines[index];
      const registryMatches = Object.values(RUNTIME_PATH_REGISTRY).filter((entry) =>
        entry.legacyPrefixes.some((prefix) => line.includes(prefix.replace(/\/$/, ''))),
      );
      if (!registryMatches.length) continue;
      const nearby = lines.slice(Math.max(0, index - 2), index + 3).join('\n');
      const writeMarkers = WRITE_MARKERS.filter((marker) => nearby.includes(marker));
      findings.push({
        file: relativePath,
        line: index + 1,
        registryKeys: registryMatches.map((entry) => entry.key),
        writeMarkers,
        likelyWriter: writeMarkers.length > 0,
        excerpt: line.trim().slice(0, 240),
      });
    }
  }
  return findings.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);
}

export function buildMigrationManifest(findings, registry) {
  return {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    safety: {
      destructiveGitCommandsAllowed: false,
      copyBeforeSwitch: true,
      sha256Required: true,
      rollbackRequired: true,
    },
    migrations: Object.values(registry.entries).map((entry) => ({
      key: entry.key,
      rootKind: entry.rootKind,
      legacyPrefixes: entry.legacyPrefixes,
      destination: entry.resolvedExternalPath,
      preservation: entry.preservation,
      reconciliation: entry.reconciliation,
      producerReferences: findings.filter((finding) => finding.registryKeys.includes(entry.key)),
    })),
  };
}

export function buildAcceptancePowerShell(registry) {
  const root = registry.runtimeRoot.replaceAll("'", "''");
  const workspace = registry.openClawWorkspaceRoot.replaceAll("'", "''");
  return `# Generated by Runtime Boundary Workbench V1\n$ErrorActionPreference = 'Stop'\n$RepoRoot = Join-Path $env:USERPROFILE 'Documents\\GitHub\\stephan-os'\n$RuntimeRoot = '${root}'\n$OpenClawWorkspace = '${workspace}'\n\nif (-not (Test-Path $RepoRoot)) { throw "Canonical repository missing: $RepoRoot" }\nNew-Item -ItemType Directory -Force -Path $RuntimeRoot | Out-Null\nNew-Item -ItemType Directory -Force -Path $OpenClawWorkspace | Out-Null\n\nPush-Location $RepoRoot\ntry {\n  $before = @(git status --porcelain=v1)\n  $beforeStatusExitCode = $LASTEXITCODE\n  node --test shared/agents/runtimeBoundaryRegistry.test.mjs shared/agents/dreamRuntimeBoundary.test.mjs scripts/runtime-boundary-workbench.test.mjs scripts/migrate-dream-runtime-boundary.test.mjs\n  $testExitCode = $LASTEXITCODE\n  node scripts/migrate-dream-runtime-boundary.mjs\n  $planExitCode = $LASTEXITCODE\n  $after = @(git status --porcelain=v1)\n  $afterStatusExitCode = $LASTEXITCODE\n  $sourceCleanAfter = ($afterStatusExitCode -eq 0 -and $after.Count -eq 0)\n  $verificationPassed = ($beforeStatusExitCode -eq 0 -and $testExitCode -eq 0 -and $planExitCode -eq 0 -and $afterStatusExitCode -eq 0)\n  [pscustomobject]@{\n    kind = 'runtime-boundary-acceptance-receipt'\n    runtimeRoot = $RuntimeRoot\n    openClawWorkspace = $OpenClawWorkspace\n    gitStatusBefore = $before\n    gitStatusAfter = $after\n    beforeStatusExitCode = $beforeStatusExitCode\n    testExitCode = $testExitCode\n    planExitCode = $planExitCode\n    afterStatusExitCode = $afterStatusExitCode\n    verificationPassed = $verificationPassed\n    sourceCleanAfter = $sourceCleanAfter\n    verdict = if ($verificationPassed -and $sourceCleanAfter) { 'PASS' } else { 'FAIL' }\n  } | ConvertTo-Json -Depth 8\n} finally {\n  Pop-Location\n}\n`;
}

export async function runWorkbench({ repoRoot, outputRoot }) {
  const findings = await scanRuntimeProducers(repoRoot);
  const registry = registryAsSerializableObject();
  const manifest = buildMigrationManifest(findings, registry);
  await fs.mkdir(outputRoot, { recursive: true });

  const inventory = {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    repositoryRoot: repoRoot,
    findingCount: findings.length,
    likelyWriterCount: findings.filter((item) => item.likelyWriter).length,
    findings,
  };
  const plan = `# Runtime Boundary Plan V1\n\n- Findings: ${findings.length}\n- Likely writers: ${inventory.likelyWriterCount}\n- Runtime root: \`${registry.runtimeRoot}\`\n- OpenClaw workspace root: \`${registry.openClawWorkspaceRoot}\`\n- Unknown paths fail closed: yes\n\n## Ordered implementation\n\n1. Migrate producers to \`getRuntimePath(key)\`.\n2. Copy and SHA-256 verify preserved state.\n3. Switch writers only after copy verification.\n4. Keep UI build output in external staging until deliberate publish.\n5. Run generated Battle Bridge acceptance packet.\n`;
  const testPlan = `# Runtime Boundary Test Plan V1\n\n1. Registry keys resolve beneath the approved external root.\n2. Unknown registry keys fail closed.\n3. Known legacy runtime dirt is attributed.\n4. Unpublished source dirt blocks sync.\n5. Malformed status lines block as unknown.\n6. Workbench inventory and migration manifest generate deterministically apart from timestamps.\n7. Dreams migration copies and SHA-256 verifies without deleting source.\n8. Battle Bridge acceptance leaves the canonical checkout clean.\n`;

  await Promise.all([
    fs.writeFile(path.join(outputRoot, 'runtime-producer-inventory.json'), JSON.stringify(inventory, null, 2) + '\n'),
    fs.writeFile(path.join(outputRoot, 'runtime-path-registry.json'), JSON.stringify(registry, null, 2) + '\n'),
    fs.writeFile(path.join(outputRoot, 'migration-manifest.json'), JSON.stringify(manifest, null, 2) + '\n'),
    fs.writeFile(path.join(outputRoot, 'runtime-boundary-plan.md'), plan),
    fs.writeFile(path.join(outputRoot, 'test-plan.md'), testPlan),
    fs.writeFile(path.join(outputRoot, 'battle-bridge-runtime-boundary-acceptance.ps1'), buildAcceptancePowerShell(registry)),
  ]);
  return { inventory, registry, manifest, outputRoot };
}

async function main() {
  const scriptDir = path.dirname(fileURLToPath(import.meta.url));
  const repoRoot = path.resolve(process.argv[2] || path.join(scriptDir, '..'));
  const outputRoot = path.resolve(process.argv[3] || path.join(registryAsSerializableObject().runtimeRoot, 'workbench'));
  const result = await runWorkbench({ repoRoot, outputRoot });
  process.stdout.write(`${JSON.stringify({ verdict: 'PASS', outputRoot, findings: result.inventory.findingCount, likelyWriters: result.inventory.likelyWriterCount })}\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    process.stderr.write(`${error.stack || error.message}\n`);
    process.exitCode = 1;
  });
}
